    <h2>10) المصروفات</h2>
    <p class="step">من <b>💸 المصروفات</b> سجّل المرتبات والعمولات والنقل والإيجار وغيرها. إذا اخترت الدفع تُنشأ سند صرف وقيد تلقائي.</p>

    <h2>11) المستخدمون والصلاحيات</h2>
    <p class="step">من <b>👤 المستخدمون</b> أضف مستخدمين وحدّد أدوارهم (مدير، محاسب، كاشير، أمين مخزن). كل دور يرى فقط ما يُسمح له.</p>

