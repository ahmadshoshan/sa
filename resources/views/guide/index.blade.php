    <h2>9) الشركاء وتوزيع الأرباح</h2>
    <p class="step">سجّل رأس مال كل شريك (نقدي/بضاعة/أصل) والمسحوبات من ملف الشريك. ثم من <b>💰 توزيع الأرباح</b> أنشئ توزيعًا للفترة، اعتمده، وسدّد نصيب كل شريك على دفعات.</p>
