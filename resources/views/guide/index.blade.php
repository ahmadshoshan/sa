    <h2>3) نقطة البيع POS</h2>
    <p class="step">من <b>🖥️ نقطة البيع</b>: امسح الباركود أو ابحث عن الصنف، أضفه للسلة، عدّل الكمية والسعر، اختر العميل وطريقة الدفع، ثم اضغط <b>إتمام البيع</b>. يُخصم المخزون ويُحدّث رصيد العميل تلقائيًا.</p>

